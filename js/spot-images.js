// 获取景点图片（优先真实图，降级 picsum）
export function getSpotImages(spotName, provName, count = 3) {
  const real = SPOT_IMAGES[spotName];
  const imgs = [];
  if (real) {
    for (let i = 0; i < Math.min(count, real.length); i++) imgs.push(real[i]);
  }
  // 不够的用 picsum 补（seed 用景点名保证稳定）
  while (imgs.length < count) {
    imgs.push('https://picsum.photos/seed/' + encodeURIComponent(provName + spotName + imgs.length) + '/600/450');
  }
  return imgs;
}

// 获取封面图（卡片用，小尺寸）
export function getSpotCover(spotName, provName) {
  const real = SPOT_IMAGES[spotName];
  if (real && real.length > 0) return real[0];
  return 'https://picsum.photos/seed/' + encodeURIComponent(provName + spotName) + '/400/240';
}
